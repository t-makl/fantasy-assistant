const assert = require('node:assert/strict');
const {matchesFilters,compare}=require('../static/board-utils.js');
const p={name:'Test Player',team:'DEN',position:'C'},r={tags:'Assists, Injury Concern',tier:'Tier 2',notes:'interesting'};
assert.equal(matchesFilters(p,r,null,{nbaTeam:'DEN'},12),true);
assert.equal(matchesFilters(p,r,null,{nbaTeam:'LAL'},12),false);
assert.equal(matchesFilters(p,r,null,{excluded:{tags:['injury concern']}},12),false);
assert.equal(matchesFilters(p,r,null,{excluded:{tiers:['Tier 2']}},12),false);
assert.equal(matchesFilters(p,r,null,{excluded:{positions:['C']}},12),false);
assert.equal(matchesFilters(p,r,null,{tags:['assists'],excluded:{positions:['PG']}},12),true);
assert.equal(matchesFilters(p,r,null,{tags:['assists'],excluded:{tags:['assists']}},12),false);
assert.equal(matchesFilters(p,{},null,{excluded:{tiers:['__none']}},12),false);
assert.equal(matchesFilters(p,r,{teamId:4},{availability:'mine'},12),false);
assert.equal(compare(1,3,'tov'),1);
assert.equal(compare(30,20,'pts'),1);
assert.equal(compare(null,20,'pts'),0);
assert.equal(compare(15,10,'fga'),0);
assert.equal(compare(7,3,'fta'),0);
assert.equal(compare(10,10,'pts'),0);
const {uniqueTags}=require('../static/board-utils.js');
assert.equal(JSON.stringify(uniqueTags(' Assists, assists, , ASSISTS, Blocks ')),JSON.stringify(['Assists','Blocks']));
assert.equal(JSON.stringify(uniqueTags(['Assists',' assists ','Blocks'])),JSON.stringify(['Assists','Blocks']));
assert.equal(matchesFilters(p,r,null,{tags:['ASSISTS','injury concern']},12),true);
assert.equal(matchesFilters(p,r,null,{tags:['assists','blocks']},12),false);
console.log('19 board filtering, tag and comparison checks passed');
